"use strict";
const {app,BrowserWindow,ipcMain}=require("electron");
const fs=require("node:fs"),os=require("node:os"),path=require("node:path"),assert=require("node:assert/strict");
const {PythonAgentClient}=require("../electron/python-agent-client.cjs");
const {AgentService,createAgentIpcHandlers}=require("../electron/agent-service.cjs");
app.whenReady().then(async()=>{
  const temp=fs.mkdtempSync(path.join(os.tmpdir(),"p2at-prompt-"));
  const renderer=path.resolve(__dirname,"../renderer");
  const client=new PythonAgentClient({memoryPath:path.join(temp,"synthetic.sqlite3")});
  const service=new AgentService({client});
  const calls=[],request=client.request.bind(client);client.request=(method,...args)=>{calls.push(method);return request(method,...args);};
  const win=new BrowserWindow({show:false,width:1100,height:850,useContentSize:true,webPreferences:{sandbox:true,contextIsolation:true,offscreen:true,preload:path.resolve(__dirname,"../electron/preload.cjs")}});
  const handlers=createAgentIpcHandlers(service,e=>e.sender===win.webContents);
  ipcMain.handle("agent:inspect-prompt",handlers.inspectPrompt);
  ipcMain.handle("agent:save-prompts",handlers.savePrompts);
  const html=fs.readFileSync(path.join(renderer,"index.html"),"utf8").replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,"")
    .replace('<link rel="stylesheet" href="agent-panel.css">',`<style>${fs.readFileSync(path.join(renderer,"agent-panel.css"),"utf8")}</style>`);
  const run=code=>win.webContents.executeJavaScript(code);
  const wait=async condition=>{for(let i=0;i<160;i++){if(await run(condition))return;await new Promise(r=>setTimeout(r,40));}throw Error("Inspector UI timed out");};
  try{
    await win.loadURL("data:text/html;charset=utf-8,"+encodeURIComponent(html));
    await run(fs.readFileSync(path.join(renderer,"prompt-inspector.js"),"utf8"));
    await run(`document.querySelector('#plannerView').hidden=true;document.querySelector('#settingsView').hidden=false;document.querySelector('#desktopBridgeStatus').hidden=true;document.querySelector('#promptInspector').open=true;`);
    await new Promise(r=>setTimeout(r,60));assert.deepEqual(calls,[]);
    await run(`document.querySelector('#inspectPrompt').click()`);await wait(`!document.querySelector('#promptInspectionText').hidden`);
    assert.deepEqual(calls,["inspect_prompt"]);
    assert.match(await run(`document.querySelector('#promptInspectionStatus').textContent`),/尚未连接/);
    await service.configure({baseUrl:"http://127.0.0.1:9999/v1",apiKey:"PRIVATE_KEY_CANARY"});
    await service.restoreConversation([{role:"user",content:"PRIVATE_HISTORY_CANARY"},{role:"assistant",content:"PRIVATE_REPLY_CANARY"}]);
    await client.request("rag_configure",{profiles:null,unavailable:true});
    const start=calls.length;
    await run(`document.querySelector('#inspectPrompt').click()`);await wait(`!document.querySelector('#inspectPrompt').disabled`);
    assert.deepEqual(calls.slice(start),["inspect_prompt"]);
    const result=await run(`({text:document.querySelector('#promptInspectionText').textContent,status:document.querySelector('#promptInspectionStatus').textContent,chat:document.querySelector('#agentMessages').textContent})`);
    assert.match(result.text,/MEMORY_CONTEXT_DATA/);assert.match(result.text,/Retrieval is currently unavailable/);
    assert.doesNotMatch(JSON.stringify(result),/PRIVATE_/);assert.doesNotMatch(result.chat,/You are a concise/);
    const direct=await client.request("inspect_prompt");assert.equal(result.text,direct.text);
    await run(`document.querySelector('#promptInspector').scrollIntoView()`);await new Promise(r=>setTimeout(r,150));
    const output=path.resolve(__dirname,"../../../docs/assets/screenshots/p2at-028a");fs.mkdirSync(output,{recursive:true});
    fs.writeFileSync(path.join(output,"prompt-inspector.png"),(await win.webContents.capturePage()).toPNG());
    service.active={kind:"synthetic-run"};
    await run(`document.querySelector('#inspectPrompt').click()`);await wait(`!document.querySelector('#inspectPrompt').disabled`);
    assert.equal(await run(`document.querySelector('#promptInspectionText').hidden`),true);
    assert.match(await run(`document.querySelector('#promptInspectionStatus').textContent`),/操作结束/);
    service.active=null;
    await run(`document.querySelector('#promptInspector').open=false`);await new Promise(r=>setTimeout(r,60));
    assert.equal(await run(`document.querySelector('#promptInspectionText').textContent`),"");
    await run(fs.readFileSync(path.join(renderer,"prompt-editor.js"),"utf8"));
    await run(`document.querySelector('#settingsView').hidden=true;document.querySelector('#agentView').hidden=false;document.querySelector('#openPromptEditor').click()`);
    await wait(`!document.querySelector('#savePromptBlocks').disabled`);
    assert.equal(await run(`document.querySelectorAll('#promptEditorBlocks textarea').length`),4);
    await run(`document.querySelector('#prompt-block-base').value='You are a concise assistant. CUSTOM_UI_FIXTURE';document.querySelector('#savePromptBlocks').click()`);
    await wait(`document.querySelector('#promptEditorStatus').textContent.includes('已保存')`);
    assert.match((await client.request("inspect_prompt")).text,/CUSTOM_UI_FIXTURE/);
    client.terminate();
    assert.match((await client.request("inspect_prompt")).text,/CUSTOM_UI_FIXTURE/);
    await new Promise(r=>setTimeout(r,120));fs.writeFileSync(path.join(output,"prompt-editor.png"),(await win.webContents.capturePage()).toPNG());
    service.active={kind:"synthetic-run"};
    await run(`document.querySelector('#savePromptBlocks').click()`);await wait(`!document.querySelector('#savePromptBlocks').disabled`);
    assert.match(await run(`document.querySelector('#promptEditorStatus').textContent`),/操作结束/);service.active=null;
    await run(`window.confirm=()=>true;document.querySelector('#resetPromptBlocks').click()`);await wait(`!document.querySelector('#savePromptBlocks').disabled`);
    assert.doesNotMatch((await client.request("inspect_prompt")).text,/CUSTOM_UI_FIXTURE/);
    console.log("PASS: four editable blocks, actual save, process restart persistence, busy-save rejection, confirmed default reset");
    console.log("PASS: production Python/preload/settings inspector; explicit read only, exact text, state labels, no private data/chat writes, busy rejection, stale clearing; zero network");
  }finally{win.destroy();client.terminate();ipcMain.removeHandler("agent:inspect-prompt");ipcMain.removeHandler("agent:save-prompts");app.quit();}
}).catch(error=>{console.error(error);app.exit(1)});
